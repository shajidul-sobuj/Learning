package Operators;

public class Arithmetic{
    public static void main(String[] args){

        // Arithmetic Operators are : +, -, *, /, +=, -=, *=, /=, ++, --

        int a = 5;
        int b = 10;


        int c = a+b;
        System.out.println(c);
        
        c = (a-b);
        System.out.println(c);

        c = (a*b);
        System.out.println(c);

        c = (a/b);
        System.out.println(c);

        c = (a&b);
        System.out.println(c);

        c = c + 2;
        System.out.println(c);

        c += 2;
        System.out.println(c);


        c++;
        System.out.println(c);

        c--;
        System.out.println(c);





    }
}